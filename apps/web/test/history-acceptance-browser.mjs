import assert from 'node:assert/strict'

export async function verifyHistory(page, baseUrl, screenshotDir) {
  const errors = []
  page.on('pageerror', error => errors.push(String(error)))
  const goto = async path => { await page.goto(baseUrl + path); await page.waitForFunction(() => !!window.historyFixture) }
  const hidden = () => page.getByRole('img', { name: '未公开底牌', exact: true }).count()
  const auditRequests = () => page.evaluate(() => window.historyFixture.requests.filter(r => r.includes('auditReveal')).length)
  const h = '10000000-0000-4000-8000-000000000001'
  const s = '22222222-2222-4222-8222-222222222222'
  await goto('/history?from=2026-09-14T01:02:03.123456Z')
  await page.getByRole('link', { name: '第 1 手 查看流程 ↗' }).waitFor()
  assert.equal(await page.locator('.history-group').count(), 3)
  await page.getByRole('button', { name: '筛选手牌', exact: true }).click()
  await page.getByLabel('用户位置').selectOption('BB')
  await page.getByRole('button', { name: '查找历史场次与人物' }).click()
  await page.getByRole('button', { name: '按此人物配置筛选' }).first().waitFor()
  const before = await page.evaluate(() => window.historyFixture.requests.filter(r => r.startsWith('/api/hands?')).length)
  await page.getByRole('button', { name: '下一批', exact: true }).click()
  await page.waitForTimeout(100)
  assert.equal(await page.evaluate(() => window.historyFixture.requests.filter(r => r.startsWith('/api/hands?')).length), before)
  await page.getByRole('button', { name: '按此人物配置筛选' }).first().click()
  await page.getByRole('button', { name: '应用筛选' }).click()
  assert.equal(new URL(page.url()).searchParams.get('from'), '2026-09-14T01:02:03.123456Z')
  assert.equal(new URL(page.url()).searchParams.get('configSnapshotKey'), '1'.repeat(64))
  assert.equal(new URL(page.url()).searchParams.has('personaName'), false)
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await page.getByRole('link', { name: '第 4 手 查看流程 ↗' }).waitFor()
  const nextUrl = page.url()
  await page.reload()
  await page.getByRole('link', { name: '第 4 手 查看流程 ↗' }).waitFor()
  assert.equal(page.url(), nextUrl)
  await page.goBack()
  await page.getByRole('link', { name: '第 1 手 查看流程 ↗' }).waitFor()
  const listUrl = page.url()
  await page.getByRole('link', { name: '第 1 手 查看流程 ↗' }).click()
  await page.getByRole('button', { name: '揭示全部底牌' }).waitFor()
  assert((await hidden()) > 0)
  assert.equal(await auditRequests(), 0)
  await page.getByRole('button', { name: '揭示全部底牌' }).click()
  await page.getByRole('button', { name: '恢复默认隐藏' }).waitFor()
  await page.waitForTimeout(100)
  assert.equal(await hidden(), 0)
  await page.getByRole('button', { name: '恢复默认隐藏' }).click()
  assert((await hidden()) > 0)
  await page.getByRole('link', { name: '返回历史', exact: false }).first().click()
  assert.equal(page.url(), listUrl)
  console.log('PASS filters, pagination, refresh/back, cached audit isolation, reveal/hide')

  await goto(`/hands/${h}?view=auditReveal`)
  await page.getByRole('button', { name: '揭示全部底牌' }).waitFor()
  assert.equal(new URL(page.url()).search, '')
  assert.equal(await auditRequests(), 0)
  await page.evaluate(() => window.historyFixture.auditError(503))
  await page.getByRole('button', { name: '揭示全部底牌' }).click()
  await page.getByText('揭牌读取失败，已恢复默认隐藏').waitFor()
  assert((await hidden()) > 0)
  await page.evaluate(() => window.historyFixture.auditError(0))
  await page.getByRole('button', { name: '重新读取', exact: true }).click()
  await page.waitForTimeout(100)
  assert.equal(await hidden(), 0)
  await page.getByRole('link', { name: '关联调用', exact: true }).click()
  await page.getByRole('link', { name: '返回本手流程', exact: true }).waitFor()
  await page.getByRole('link', { name: '返回本手流程', exact: true }).click()
  await page.getByRole('heading', { name: '当前手流程' }).waitFor()
  await page.evaluate(() => window.historyFixture.advance())
  await page.getByText('跟注 40', { exact: true }).waitFor()
  assert.equal(await page.locator('.history-actions li').count(), 1)
  await page.evaluate(() => window.historyFixture.complete())
  await page.getByText('本手已完成', { exact: true }).waitFor()
  await page.getByRole('link', { name: '打开已完成手详情' }).click()
  await page.getByRole('button', { name: '揭示全部底牌' }).waitFor()
  assert((await hidden()) > 0)
  await page.getByRole('link', { name: '关联调用', exact: true }).click()
  await page.getByRole('link', { name: '返回已完成手详情', exact: true }).click()
  await page.getByRole('button', { name: '揭示全部底牌' }).waitFor()
  assert((await hidden()) > 0)
  await page.getByRole('link', { name: '返回本场牌桌', exact: true }).click()
  await page.getByRole('heading', { name: '牌桌', exact: true }).waitFor()
  console.log('PASS deep link, audit error/retry, call navigation, current action/completion/table')

  await goto(`/hands/${h}`)
  await page.getByRole('button', { name: '揭示全部底牌' }).waitFor()
  await page.evaluate(() => window.historyFixture.complete())
  await page.getByRole('link', { name: '返回本场牌桌', exact: true }).click()
  await page.getByRole('heading', { name: '牌桌', exact: true }).waitFor()
  await page.evaluate(path => { window.history.pushState(null, '', path); window.dispatchEvent(new PopStateEvent('popstate')) }, `/sessions/${s}/current-hand`)
  await page.getByText('当前无进行中手牌，以下为上一手', { exact: true }).waitFor()
  assert.equal(await page.getByText('场次已进入新的一手').count(), 0)
  await page.evaluate(() => window.historyFixture.next())
  await page.getByRole('heading', { name: '当前手流程' }).waitFor()
  await page.getByText('场次已进入新的一手').waitFor()
  assert.equal(await page.getByText('当前无进行中手牌，以下为上一手', { exact: true }).count(), 0)
  console.log('PASS direct entry between hands tracks displayed summary identity')

  await goto(`/sessions/${s}/current-hand`)
  await page.getByRole('heading', { name: '当前手流程' }).waitFor()
  await page.evaluate(() => { window.historyFixture.advance(); window.historyFixture.hold(true); window.historyFixture.complete() })
  await page.getByText('本手已完成', { exact: true }).waitFor()
  await page.evaluate(() => { window.historyFixture.next(); window.historyFixture.hold(false) })
  await page.getByText('场次已进入新的一手').waitFor()
  await page.waitForTimeout(100)
  assert.equal(await page.getByText('本手已完成', { exact: true }).count(), 0)
  assert.equal(await page.locator('.history-actions li').count(), 0)
  await page.evaluate(() => window.historyFixture.disconnect())
  await page.waitForTimeout(1500)
  await page.getByRole('heading', { name: '当前手流程' }).waitFor()
  await page.evaluate(() => window.historyFixture.abort())
  await page.getByText('当前没有进行中的手牌', { exact: true }).waitFor()
  assert.equal(await page.locator('.history-actions li').count(), 0)
  console.log('PASS late completion/new hand, reconnect, aborted hand')

  await goto(`/hands/${h}`)
  await page.getByRole('button', { name: '揭示全部底牌' }).waitFor()
  await page.evaluate(() => window.historyFixture.hold(true))
  await page.getByRole('button', { name: '揭示全部底牌' }).click()
  await page.getByRole('button', { name: '恢复默认隐藏' }).click()
  await page.evaluate(() => window.historyFixture.hold(false))
  await page.waitForTimeout(100)
  assert((await hidden()) > 0)
  await page.evaluate(() => window.historyFixture.remove())
  await page.getByText('这手不在可查看的已完成记录中', { exact: true }).waitFor()
  assert.equal(await page.locator('.history-player').count(), 0)
  console.log('PASS late audit after hide and deleted hand')
  await goto(`/hands/${h}`)
  await page.getByRole('button', { name: '揭示全部底牌' }).waitFor()
  await page.evaluate(() => window.historyFixture.auditError(404))
  await page.getByRole('button', { name: '揭示全部底牌' }).click()
  await page.getByText('这手不在可查看的已完成记录中', { exact: true }).waitFor()
  assert.equal(await page.locator('.history-player').count(), 0)
  await goto('/hands/10000000-0000-4000-8000-000000000002')
  await page.getByRole('heading', { name: '摊牌 / 结算', exact: true }).waitFor()
  assert.equal(await page.getByText('本街无下注行动', { exact: true }).count(), 3)
  assert.equal(await page.locator('.history-pot').count(), 5)
  if(screenshotDir) await page.screenshot({path:`${screenshotDir}/history-showdown.png`})
  console.log('PASS audit 404 withdraws public, all-in runout and five pots')


  for (const [width, height] of [[360,640], [390,844], [430,850]]) {
    await page.setViewportSize({width,height})
    await goto('/history')
    await page.getByRole('link', { name: '第 1 手 查看流程 ↗' }).waitFor()
    await page.locator('summary').first().click()
    const overflow = () => page.evaluate(() => [...document.querySelectorAll('.page-content, .history-panel, .history-option, .history-filter-fields')].filter(e => e.scrollWidth > e.clientWidth + 1).map(e => e.className))
    assert.deepEqual(await overflow(), [])
    if(screenshotDir) await page.screenshot({path:`${screenshotDir}/history-${width}.png`})
    await page.getByRole('button', { name: '筛选手牌', exact: true }).click()
    await page.getByRole('button', { name: '查找历史场次与人物' }).click()
    await page.getByRole('button', { name: '按此人物配置筛选' }).first().waitFor()
    assert.deepEqual(await overflow(), [])
    await page.keyboard.press('Escape')
    await page.evaluate(() => document.documentElement.style.fontSize = '32px')
    assert.deepEqual(await overflow(), [])
    await goto(`/sessions/${s}/current-hand?count=9`)
    await page.getByRole('heading', { name: '当前手流程' }).waitFor()
    assert.deepEqual(await overflow(), [])
  }
  assert.deepEqual(errors, [])
  console.log('PASS viewport/long names/200% text/9 seats')
}
